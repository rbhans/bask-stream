// Generates src/operations.ts from the protocol spec so the SDK's operation list cannot drift.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const spec = JSON.parse(readFileSync(join(here, "../../spec/baskstream-protocol.json"), "utf8"));
const rows = Object.entries(spec.operations)
  .map(([name, op]) => `  ${JSON.stringify(name)}: { gate: ${JSON.stringify(op.gate)}, reply: ${JSON.stringify(op.reply)} },`)
  .join("\n");
const out = `// Generated by scripts/gen-operations.mjs from spec/baskstream-protocol.json. Do not edit.
export const API_VERSION = ${JSON.stringify(spec.apiVersion)};

export const OPERATIONS = {
${rows}
} as const;

export type OperationName = keyof typeof OPERATIONS;
export type Gate = (typeof OPERATIONS)[OperationName]["gate"];

export const ERROR_CODES = ${JSON.stringify(Object.keys(spec.errors))} as const;
export type ErrorCode = (typeof ERROR_CODES)[number];
`;
writeFileSync(join(here, "../src/operations.ts"), out);
console.log(`operations.ts: ${Object.keys(spec.operations).length} operations, ${Object.keys(spec.errors).length} error codes`);
